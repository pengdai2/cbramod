"""
p09k_absolute_band_power_analysis.py

Absolute-power counterpart to p09f_morphology_score_correlation.py / p09j_band_covariation_check.py.
Both of those operate on RELATIVE band power (each band's share of a window's total power, a
composition that sums to ~1 by construction) -- which p09j confirmed is tightly bound (relpower sum
= 1.027 +/- 0.020) and shows the exact signature of "one dominant component (delta) vs. a co-moving
shared remainder" (the four non-delta bands correlate +0.72 to +0.92 with EACH OTHER, while each
correlates -0.89 to -0.95 with delta). That pattern is guaranteed in RATIO space regardless of what's
actually happening physically -- it carries no information about whether real, absolute (uV^2) delta
power rises together with the other bands (a shared broadband amplitude/state factor) or trades off
against them (a genuine spectral trade-off). Only absolute power can distinguish those.

This script reconstructs the real uV signal for every window using the per-channel norm_mean_uv/
norm_std_uv persisted by p02_slice_eeg_dataset.py's process_and_normalize_slice() (needs metadata
regenerated by a p02 re-slice that includes this field -- an older meta_path without these keys
raises an explicit error rather than silently falling back to the Z-scored signal, which would
silently defeat the entire point of this script), then:
  1. Computes ABSOLUTE Welch band power (raw PSD-bin sum, no normalization by total -- so these are
     in consistent-but-uncalibrated units proportional to uV^2, not a physically calibrated uV^2/Hz;
     fine for correlation purposes since every window is computed identically) for the same 5 bands.
  2. Re-runs YASA spindle/slow-wave detection on the reconstructed real-uV signal instead of the
     Z-scored one -- YASA's detectors are calibrated against real EEG amplitude, so this should also
     fix the amplitude-related warnings seen running YASA on Z-scored data earlier in this
     investigation ("Wrong data amplitude... trimmed STD = 0.000").
  3. Correlates probability against ABSOLUTE band power (pooled + within-subject) -- the direct
     re-test of whether delta's earlier positive relationship (found using relative power) survives,
     flips, or vanishes once expressed in real, non-ratio-constrained units.
  4. Correlates delta_abspower against each other band's abspower (pooled + within-subject) -- the
     direct test of the open question: do they co-move (shared broadband factor) or trade off (a
     real spectral relationship)? Unlike the relpower version, this one is NOT guaranteed to come out
     any particular way by construction -- absolute powers have no sum-to-1 constraint.

Usage:
  python p09k_absolute_band_power_analysis.py \
      --checkpoint model.pt --manifest test_manifest.csv \
      --output-dir results/ --max-windows-per-subject 200
"""

import argparse
import json
import logging
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
import torch
from scipy.signal import welch
from tqdm import tqdm

try:
    import yasa
    HAS_YASA = True
    # yasa's "No spindles/SW were found..." messages are emitted via the logging module at WARNING
    # level regardless of the verbose=False passed to spindles_detect()/sw_detect() below -- that kwarg
    # only gates yasa's own INFO-ish prints. Most windows legitimately contain zero detected events
    # (spindles/slow-waves are transient, not present in every 30s window), so this is expected,
    # benign output, not a data-quality signal.
    #
    # A per-logger logging.getLogger("yasa").setLevel(logging.ERROR) does NOT reliably silence this --
    # yasa's own verbose=False handling appears to reset its logger's level back to WARNING internally
    # on every spindles_detect()/sw_detect() call, undoing a one-time setLevel from here. logging.
    # disable() instead sets a GLOBAL threshold checked independently of any individual logger's own
    # level (Logger.manager.disable), so it can't be undone by yasa resetting its own logger per-call.
    # ERROR (40) and CRITICAL stay visible; only WARNING (30) and below are suppressed.
    logging.disable(logging.WARNING)
except ImportError:
    HAS_YASA = False

